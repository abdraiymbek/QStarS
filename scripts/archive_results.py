#!/usr/bin/env python3
"""Lossless, verified packing of finished run directories under results/ (device transfer, 2026-10-29).

Each unit (a run directory below results/) becomes
  results/_archive/full/<name>.tar.zst       every entry byte-exact: files, symlinks, hard links, directories,
                                             modes and mtimes (stays on the archive machine, ~1/3 of raw)
  results/_archive/record/<name>.tar.zst     the run's record: inputs, logs, run manifests, metrics, output
                                             populations (RECORD_RULE); small enough to copy everywhere
  results/_archive/manifests/<name>.jsonl.zst  one line per entry: path, type, size, mode, mtime, sha256, link
plus an INDEX.json entry. <name> is the unit path with '/' -> '__'. A source directory is removed (--delete) only
after BOTH archives were decompressed and every member matched the manifest (type, size, mode, link target,
sha256) and the full archive held exactly the manifest's entries. WORKING is never packed.

    archive_results.py plan [--sizes]           units still raw, and the working set
    archive_results.py pack UNIT ...|--all [--delete] [--jobs 2] [--threads 4]
    archive_results.py verify UNIT ...|--all
    archive_results.py restore UNIT [--record] [--dest DIR]    back into results/ (or DIR)
    archive_results.py status                   totals from INDEX.json

Restoring by hand: zstd -dc --long=30 results/_archive/full/<name>.tar.zst | tar -xpf - -C results
(--long=30 is required: the archives use a 1 GiB match window so that repeated pass outputs compress)."""
import argparse, copy, fnmatch, functools, grp, hashlib, io, json, os, pwd, re, shutil, subprocess, sys, tarfile, time
import types
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / 'results'
ARCHIVE = RESULTS / '_archive'
# kept raw on every machine: the Report 24 stage-1 run with its executables and inputs, and what tests read
WORKING = ('nk167_trap/fixedT_b35', 'nk167_trap/b36_tests', 'nk167_trap/tprobe_it01', 'nk167_trap/exe*',
           'nk167_adv/transfer', 'cmfgen_ali_lambda167', 'cmfgen_ali_lambda84_long')
# packed although inside a working directory (set aside, never read by the run)
PACK_INSIDE = {'nk167_trap/fixedT_b35': ('branch_*', 'superseded')}
LONG = 30
RECORD_RULE = 1
# not in the record: native scratch, QStarS traces, radiation-field and operator dumps (all regenerated by a pass)
BULK = re.compile(r'SCRATCH|^QSTARS_(BA_TRACE|SPECTRAL|JV_SPECTRAL|RJ|JV_RAD|DIRS|STEQ_TRACE|ALI_LIN_HASH)\.bin$'
                  r'|^(JH_AT_CURRENT_TIME|EDDFACTOR.*|CONT_FREQ|STEQ_VALS|GreyDiagnostics|MOM_J_ERRORS|J_COMP|BAMAT'
                  r'|BAMATPNT|BA_ASCI_N_.*|OBS_FREQ|OBSFLUX)$')
# nor restart copies of the source populations, binary state, Fortran unit dumps, rate diagnostics, arrays, executables
STATE = re.compile(r'_IN$|^SCRTEMP$|^fort\.\d+$|PRRR$|^GENCOOL$|^POINT\d*$|\.(bin|npy|npz|exe)$|^star$')

# gettarinfo looks the owner up for every member (directory service calls on macOS)
tarfile.pwd = types.SimpleNamespace(getpwuid=functools.lru_cache(None)(pwd.getpwuid))
tarfile.grp = types.SimpleNamespace(getgrgid=functools.lru_cache(None)(grp.getgrgid))


class ArchiveError(RuntimeError):
    pass


def in_record(name, size, mode):
    return not (BULK.search(name) or STATE.search(name) or (mode & 0o111 and size > 1 << 20))


def arcname(unit):
    return unit.replace('/', '__')


def paths(unit):
    n = arcname(unit)
    return (ARCHIVE / 'full' / f'{n}.tar.zst', ARCHIVE / 'record' / f'{n}.tar.zst',
            ARCHIVE / 'manifests' / f'{n}.jsonl.zst')


def working(rel):
    return any(fnmatch.fnmatchcase(rel, w) for w in WORKING)


def units():
    out = []

    def visit(rel):
        p = RESULTS / rel
        if working(rel):
            for pat in PACK_INSIDE.get(rel, ()):
                out.extend(f'{rel}/{c.name}' for c in sorted(p.glob(pat)) if c.is_dir() and not c.is_symlink())
            return
        if any(w.startswith(rel + '/') for w in WORKING):
            for c in sorted(p.iterdir()):
                if c.is_dir() and not c.is_symlink():
                    visit(f'{rel}/{c.name}')
            return
        out.append(rel)
    for c in sorted(RESULTS.iterdir()):
        if c.name != '_archive' and c.is_dir() and not c.is_symlink():
            visit(c.name)
    return out


def entries(top):
    """Every entry below top (top included), sorted, without following symlinks."""
    yield top
    with os.scandir(top) as it:
        ch = sorted(it, key=lambda d: d.name)
    for d in ch:
        if d.is_dir(follow_symlinks=False):
            yield from entries(d.path)
        else:
            yield d.path


def raw_size(top):
    return sum(os.lstat(p).st_size for p in entries(top) if not os.path.isdir(p) or os.path.islink(p))


class Tee:
    """Reader that hashes what tarfile copies."""

    def __init__(self, f, h):
        self.f, self.h = f, h

    def read(self, n=-1):
        b = self.f.read(n)
        self.h.update(b)
        return b


def zstd_out(path, level, threads):
    # -B bounds memory (~3 GB at -T4): the default job size grows with the window and would hold GBs per thread
    return subprocess.Popen(['zstd', '-q', f'-{level}', f'-T{threads}', f'--long={LONG}', '-B256MiB', '-f', '-o',
                             str(path)], stdin=subprocess.PIPE)


def zstd_in(path):
    return subprocess.Popen(['zstd', '-dcq', f'--long={LONG}', str(path)], stdout=subprocess.PIPE)


def open_w(proc):
    t = tarfile.open(fileobj=proc.stdin, mode='w|', format=tarfile.PAX_FORMAT, bufsize=1 << 20)
    t.copybufsize = 1 << 22
    return t


def close(t, proc, what):
    t.close()
    proc.stdin.close()
    if proc.wait() != 0:
        raise ArchiveError(f'zstd failed writing {what}')


def write_archives(unit, threads):
    full, rec, man = paths(unit)
    for p in (full, rec, man):
        p.parent.mkdir(parents=True, exist_ok=True)
    part = lambda p: p.with_name(p.name + '.part')
    zf, zr = zstd_out(part(full), 9, threads), zstd_out(part(rec), 19, max(1, threads // 2))
    tf, tr = open_w(zf), open_w(zr)
    m, links = [], {}
    for path in entries(str(RESULTS / unit)):
        ti = tf.gettarinfo(path, arcname=os.path.relpath(path, RESULTS))
        e = dict(p=ti.name, mode=ti.mode & 0o7777, m=ti.mtime)   # tar keeps the permission bits only
        if ti.isreg():
            st = os.lstat(path)
            h, r = hashlib.sha256(), in_record(os.path.basename(path), ti.size, ti.mode)
            with open(path, 'rb') as f:
                if r:
                    data = f.read()
                    h.update(data)
                    tf.addfile(ti, io.BytesIO(data))
                    tr.addfile(copy.copy(ti), io.BytesIO(data))
                else:
                    tf.addfile(ti, Tee(f, h))
            e.update(t='f', s=ti.size, h=h.hexdigest(), r=int(r))
            if st.st_nlink > 1:
                links[(st.st_ino, st.st_dev)] = e['h']
        elif ti.islnk():
            # hard link to a file stored earlier in this unit; the record stores its content as a regular file
            st = os.lstat(path)
            r = in_record(os.path.basename(path), st.st_size, ti.mode)
            tf.addfile(ti)
            if r:
                with open(path, 'rb') as f:
                    data = f.read()
                ri = copy.copy(ti)
                ri.type, ri.linkname, ri.size = tarfile.REGTYPE, '', len(data)
                tr.addfile(ri, io.BytesIO(data))
            e.update(t='h', s=st.st_size, h=links[(st.st_ino, st.st_dev)], L=ti.linkname, r=int(r))
        elif ti.issym():
            tf.addfile(ti)
            e.update(t='l', L=ti.linkname)
        elif ti.isdir():
            tf.addfile(ti)
            tr.addfile(copy.copy(ti))
            e.update(t='d')
        else:
            raise ArchiveError(f'{path}: unsupported file type')
        m.append(e)
    close(tf, zf, full.name)
    close(tr, zr, rec.name)
    return m


def check(arch, m, record):
    """Decompress arch and compare every member with the manifest m (the record holds its subset)."""
    want = {e['p']: e for e in m if not record or e['t'] == 'd' or e.get('r')}
    seen = set()
    p = zstd_in(arch)
    with tarfile.open(fileobj=p.stdout, mode='r|', bufsize=1 << 20) as t:
        for x in t:
            e = want.get(x.name)
            if e is None or x.name in seen:
                raise ArchiveError(f'{arch.name}: unexpected member {x.name}')
            seen.add(x.name)
            if x.mode != e['mode'] or x.mtime != e['m']:
                raise ArchiveError(f'{arch.name}: {x.name}: mode/mtime differ')
            if e['t'] == 'f' or (record and e['t'] == 'h'):
                if not x.isreg() or x.size != e['s']:
                    raise ArchiveError(f'{arch.name}: {x.name}: type/size differ')
                h, f = hashlib.sha256(), t.extractfile(x)
                while b := f.read(1 << 22):
                    h.update(b)
                if h.hexdigest() != e['h']:
                    raise ArchiveError(f'{arch.name}: {x.name}: content differs')
            elif e['t'] in 'hl':
                if not (x.islnk() if e['t'] == 'h' else x.issym()) or x.linkname != e['L']:
                    raise ArchiveError(f'{arch.name}: {x.name}: link differs')
            elif not x.isdir():
                raise ArchiveError(f'{arch.name}: {x.name}: not a directory')
    if p.wait() != 0:
        raise ArchiveError(f'{arch.name}: zstd failed')
    if len(seen) != len(want):
        raise ArchiveError(f'{arch.name}: {len(want) - len(seen)} manifest entries missing')


def read_manifest(unit):
    out = subprocess.run(['zstd', '-dcq', str(paths(unit)[2])], capture_output=True, check=True).stdout
    return [json.loads(x) for x in out.splitlines()]


def sha256_file(p):
    h = hashlib.sha256()
    with open(p, 'rb') as f:
        while b := f.read(1 << 22):
            h.update(b)
    return h.hexdigest()


def pack(unit, threads, delete, index_entry):
    """Archive one unit (or re-verify an existing archive) and optionally remove its source. Returns the INDEX entry."""
    full, rec, man = paths(unit)
    src = RESULTS / unit
    t0 = time.time()
    if index_entry is None:
        m = write_archives(unit, threads)
        for a, record in ((full.with_name(full.name + '.part'), False), (rec.with_name(rec.name + '.part'), True)):
            check(a, m, record)
        mp = man.with_name(man.name + '.part')
        subprocess.run(['zstd', '-q', '-19', f'-T{threads}', '-f', '-o', str(mp)], check=True,
                       input=b''.join(json.dumps(e, separators=(',', ':')).encode() + b'\n' for e in m))
        for p in (full, rec, man):
            p.with_name(p.name + '.part').replace(p)
        files = [e for e in m if e['t'] in 'fh']
        index_entry = dict(unit=unit, packed=time.strftime('%Y-%m-%d %H:%M'), record_rule=RECORD_RULE,
                           entries=len(m), files=len(files), symlinks=sum(e['t'] == 'l' for e in m),
                           raw_bytes=sum(e['s'] for e in m if e['t'] == 'f'),
                           record_raw_bytes=sum(e['s'] for e in files if e.get('r')),
                           full_bytes=full.stat().st_size, record_bytes=rec.stat().st_size,
                           manifest_bytes=man.stat().st_size, record_sha256=sha256_file(rec),
                           manifest_sha256=sha256_file(man), source_removed=False)
    elif delete and src.exists():
        m = read_manifest(unit)
        check(full, m, False)
        check(rec, m, True)
    if delete and src.exists():
        shutil.rmtree(src)
        index_entry['source_removed'] = True
        index_entry['removed'] = time.strftime('%Y-%m-%d %H:%M')
    index_entry['seconds'] = round(time.time() - t0)
    return index_entry


def load_index():
    p = ARCHIVE / 'INDEX.json'
    return json.loads(p.read_text()) if p.exists() else dict(format=1, long=LONG, units={})


def save_unit(unit, entry):
    """Merge one INDEX entry under a lock (retain_runs.py may pack while another packer runs)."""
    import fcntl
    ARCHIVE.mkdir(parents=True, exist_ok=True)
    with open(ARCHIVE / '.index.lock', 'w') as lk:
        fcntl.flock(lk, fcntl.LOCK_EX)
        ix = load_index()
        ix['units'][unit] = entry
        tmp = ARCHIVE / 'INDEX.json.part'
        tmp.write_text(json.dumps(ix, indent=1, sort_keys=True) + '\n')
        tmp.replace(ARCHIVE / 'INDEX.json')


def note_working_parent(unit):
    # a unit set aside inside a working run: say where it went in that run's README
    for parent in PACK_INSIDE:
        readme = RESULTS / parent / 'README.txt'
        if unit.startswith(parent + '/') and readme.exists():
            with open(readme, 'a') as f:
                f.write(f"{time.strftime('%Y-%m-%d %H:%M')}: {unit[len(parent) + 1:]}/ packed losslessly to "
                        f"results/_archive/full/{arcname(unit)}.tar.zst (scripts/archive_results.py restore {unit})\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('cmd', choices=('plan', 'pack', 'verify', 'restore', 'status'))
    ap.add_argument('units', nargs='*')
    ap.add_argument('--all', action='store_true')
    ap.add_argument('--delete', action='store_true', help='remove each source after both archives verified')
    ap.add_argument('--jobs', type=int, default=2)
    ap.add_argument('--threads', type=int, default=4, help='zstd threads per unit')
    ap.add_argument('--record', action='store_true', help='restore: the record instead of the full archive')
    ap.add_argument('--dest', type=Path, default=RESULTS)
    ap.add_argument('--sizes', action='store_true')
    a = ap.parse_args()
    ix = load_index()
    if a.cmd == 'plan':
        for u in units():
            state = 'packed, source kept' if u in ix['units'] else 'raw'
            print(f'{raw_size(RESULTS / u) / 1e9:8.2f} GB  {u}  ({state})' if a.sizes else f'{u}  ({state})')
        print('working set (never packed):', ', '.join(WORKING))
        return
    if a.cmd == 'status':
        us = ix['units'].values()
        g = lambda k: sum(u[k] for u in us) / 1e9
        print(f"{len(ix['units'])} units: raw {g('raw_bytes'):.1f} GB -> full {g('full_bytes'):.1f} GB, "
              f"record {g('record_bytes'):.2f} GB (of {g('record_raw_bytes'):.1f} GB), manifests "
              f"{g('manifest_bytes'):.2f} GB; sources removed: {sum(u['source_removed'] for u in us)}")
        return
    todo = units() if a.all else a.units
    if a.cmd == 'restore':
        for u in todo:
            arch = paths(u)[1 if a.record else 0]
            if (a.dest / u).exists():
                sys.exit(f'{a.dest / u} exists')
            a.dest.mkdir(parents=True, exist_ok=True)
            z = zstd_in(arch)
            t = subprocess.run(['tar', '-xpf', '-', '-C', str(a.dest)], stdin=z.stdout)
            if z.wait() != 0 or t.returncode != 0:
                sys.exit(f'restore of {u} failed')
            print(f'restored {u} into {a.dest}')
        return
    if a.cmd == 'verify':
        for u in (ix['units'] if a.all else todo):
            m = read_manifest(u)
            check(paths(u)[0], m, False)
            check(paths(u)[1], m, True)
            print(f'ok {u}')
        return
    jobs = [u for u in todo if u not in ix['units'] or (a.delete and (RESULTS / u).exists())]
    failed = []
    with ProcessPoolExecutor(max_workers=a.jobs) as ex:
        fut = {ex.submit(pack, u, a.threads, a.delete, ix['units'].get(u)): u for u in jobs}
        for f in as_completed(fut):
            u = fut[f]
            try:
                e = f.result()
            except Exception as err:   # leave the source untouched; .part files are overwritten next time
                failed.append(u)
                print(f'FAILED {u}: {err}', flush=True)
                continue
            save_unit(u, e)
            if e['source_removed']:
                note_working_parent(u)
            print(f"{u}: {e['raw_bytes'] / 1e9:.2f} GB -> full {e['full_bytes'] / 1e9:.2f}, record "
                  f"{e['record_bytes'] / 1e6:.1f} MB, {e['seconds']} s{', source removed' if e['source_removed'] else ''}",
                  flush=True)
    if failed:
        sys.exit(f'{len(failed)} units failed: {" ".join(failed)}')


if __name__ == '__main__':
    main()
